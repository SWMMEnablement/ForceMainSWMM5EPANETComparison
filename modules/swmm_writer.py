    def create_force_main_system(self, config):
        """
        Create complete force main system
        
        config = {
            'project_title': str,
            'flow_units': str,
            'wet_well': {
                'id': str,
                'invert': float,
                'max_depth': float,
                'init_depth': float,
                'area': float
            },
            'pump': {
                'id': str,
                'from': str,
                'to': str,
                'curve': str,
                'startup': float,
                'shutoff': float,
                'curve_data': [(flow, head), ...]
            },
            'force_main': {
                'id': str,
                'from': str,
                'to': str,
                'diameter': float,
                'length': float,
                'roughness': float
            },
            'discharge_node': {
                'id': str,
                'elevation': float,
                'max_depth': float,
                'surcharge_depth': float
            }
        }
        """
        
        # Update options based on config
        if 'flow_units' in config:
            self.options['FLOW_UNITS'] = config['flow_units']
        
        content = []
        
        # Header sections
        content.extend(self.create_header_sections(config.get('project_title', self.title)))
        
        # Extract commonly used variables
        ww = config['wet_well']
        pump = config.get('pump', {})
        
        # Junctions section
        content.append("[JUNCTIONS]")
        content.append(";;Name           Elevation  MaxDepth   InitDepth  SurDepth   Aponded   ")
        content.append(";;-------------- ---------- ---------- ---------- ---------- ----------")
        
        # Add intermediate node for pump discharge
        pump_discharge_node = config['force_main']['from']
        content.append(f"{pump_discharge_node:<16} {ww['invert'] + 1.0:<10.2f} {2.0:<10.2f} {0.0:<10.2f} {100.0:<10.2f} {0.0:<10.2f}")
        
        # Add discharge node with surcharge capability
        dn = config['discharge_node']
        # Ensure surcharge depth is at least 100 for force main nodes
        surcharge_depth = max(dn.get('surcharge_depth', 100.0), 100.0)
        content.append(f"{dn['id']:<16} {dn['elevation']:<10.2f} {dn['max_depth']:<10.2f} {0.0:<10.2f} {surcharge_depth:<10.2f} {0.0:<10.2f}")
        content.append("")
        
        # Outfalls section
        content.append("[OUTFALLS]")
        content.append(";;Name           Elevation  Type       Stage Data       Gated    Route To        ")
        content.append(";;-------------- ---------- ---------- ---------------- -------- ----------------")
        # Set outfall elevation lower than discharge node for gravity flow downhill
        outfall_elevation = dn['elevation'] - 2.0  # 2 meters below discharge node for adequate slope
        content.append(f"{'OUTFALL1':<16} {outfall_elevation:<10.2f} {'FREE':<10} {'':<16} {'NO':<8} {'':<16}")
        content.append("")
        
        # Storage section for wet well tank - realistic pump station design
        content.append("[STORAGE]")
        content.append(";;Name           Elev.    MaxDepth   InitDepth  Shape      Curve Name/Params            N/A      Fevap    Psi      Ksat     IMD     ")
        content.append(";;-------------- -------- ---------- ----------- ---------- ---------------------------- -------- -------- -------- -------- --------")
        content.append(f"{ww['id']:<16} {ww['invert']:<8.2f} {ww['max_depth']:<10.2f} {ww['init_depth']:<10.2f} {'FUNCTIONAL':<10} {ww['area']:<8.2f} 0 0 0 {0.0:<8.2f} {0.0:<8.2f} {0.0:<8.2f} {0.0:<8.2f}")
        content.append("")
        
        # Conduits section
        content.append("[CONDUITS]")
        content.append(";;Name           From Node        To Node          Length     Roughness  InOffset   OutOffset  InitFlow   MaxFlow   ")
        content.append(";;-------------- ---------------- ---------------- ---------- ---------- ---------- ---------- ---------- ----------")
        
        fm = config['force_main']
        content.append(f"{fm['id']:<16} {fm['from']:<16} {fm['to']:<16} {fm['length']:<10.2f} {fm['roughness']:<10.4f} {0.0:<10.2f} {0.0:<10.2f} {0.0:<10.2f} {0.0:<10.2f}")
        
        # Add gravity conduit from discharge node to outfall
        content.append(f"{'GRAVITY1':<16} {dn['id']:<16} {'OUTFALL1':<16} {100.0:<10.2f} {0.013:<10.4f} {0.0:<10.2f} {0.0:<10.2f} {0.0:<10.2f} {0.0:<10.2f}")
        content.append("")
        
        # Pumps section
        content.append("[PUMPS]")
        content.append(";;Name           From Node        To Node          Pump Curve       Status   Sartup Shutoff ")
        content.append(";;-------------- ---------------- ---------------- ---------------- ------ -------- --------")
        
        pump = config['pump']
        content.append(f"{pump['id']:<16} {pump['from']:<16} {pump['to']:<16} {pump['curve']:<16} {'ON':<6} {pump['startup']:<8.2f} {pump['shutoff']:<8.2f}")
        content.append("")
        
        # XSections section
        content.append("[XSECTIONS]")
        content.append(";;Link           Shape        Geom1            Geom2      Geom3      Geom4      Barrels    Culvert   ")
        content.append(";;-------------- ------------ ---------------- ---------- ---------- ---------- ---------- ----------")
        
        # Force main cross-section
        # Geom2 for FORCE_MAIN should be HW C coefficient (not Manning's n)
        hw_c = 120 if fm['roughness'] < 1 else fm['roughness']  # Convert Manning's n to HW C if needed
        content.append(f"{fm['id']:<16} {'FORCE_MAIN':<12} {fm['diameter']:<16.3f} {hw_c:<10.3f} {0:<10.3f} {0:<10.3f} {1:<10} {0:<10}")
        
        # Gravity conduit cross-section
        gravity_diameter = max(0.2, fm['diameter'] * 1.5)  # Size appropriately
        content.append(f"{'GRAVITY1':<16} {'CIRCULAR':<12} {gravity_diameter:<16.3f} {0:<10.3f} {0:<10.3f} {0:<10.3f} {1:<10} {0:<10}")
        content.append("")
        
        # Curves section
        content.append("[CURVES]")
        content.append(";;Name           Type       X-Value    Y-Value   ")
        content.append(";;-------------- ---------- ---------- ----------")
        
        # First line has curve name and pump type
        if pump['curve_data']:
            flow, head = pump['curve_data'][0]
            content.append(f"{pump['curve']:<16} {'Pump3':<10} {flow:<10.4f} {head:<10.2f}")
            
            # Subsequent lines have only curve name and values
            for flow, head in pump['curve_data'][1:]:
                content.append(f"{pump['curve']:<16} {'':<10} {flow:<10.4f} {head:<10.2f}")
        content.append("")
        
        # Controls section for pump operation
        content.append("[CONTROLS]")
        content.append(f"RULE R1")
        content.append(f"IF NODE {ww['id']} DEPTH > {pump['startup']}")
        content.append(f"THEN PUMP {pump['id']} STATUS = ON")
        content.append("")
        content.append(f"RULE R2")
        content.append(f"IF NODE {ww['id']} DEPTH < {pump['shutoff']}")
        content.append(f"THEN PUMP {pump['id']} STATUS = OFF")
        content.append("")
        
        # Coordinates section for network visualization
        content.extend(self.create_coordinates_section(config, 'force_main'))
        
        # No polygons section needed without subcatchments
        
        # Report section
        content.extend(self.create_report_section())
        
        # Files section removed to avoid hotstart file errors
        
        # DWF (Dry Weather Flow) for constant inflow to wet well - at end of file
        content.append("[DWF]")
        content.append(";;Node           Constituent      Baseline   Pattern   ")
        content.append(";;-------------- ---------------- ---------- ----------")
        ww = config['wet_well']
        # Use pump flow rate as the constant inflow (or default value)
        pump = config.get('pump', {})
        inflow_rate = pump.get('flow', 0.15)  # Default 0.15 m³/s if not specified
        content.append(f"{ww['id']:<16} {'FLOW':<16} {inflow_rate:<10.6f} {'':<10}")
        content.append("")
        
        return "\n".join(content)
    
