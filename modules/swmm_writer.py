import os
from datetime import datetime
import numpy as np

class SWMMInputGenerator:
    """
    Generate SWMM5 input files for force main systems
    
    MODELING RULES FOR SWMM5-EPANET CONSISTENCY:
    - Use FORCE_MAIN link type (not CONDUIT) with proper XSECTIONS
    - Physical parameters (diameter, length, roughness) must match EPANET
    - Use DYNWAVE routing for accurate pressure simulation (Rule 7)
    - Friction equation (H-W or D-W) must match EPANET settings
    - Wet well modeled as STORAGE node for realistic pump station
    - Pump curves must be identical to EPANET pump curves
    - Minor losses included in XSECTIONS configuration
    - Results should match EPANET within 5-10% tolerance
    """
    
    def __init__(self):
        self.title = "Force Main System"
        self.options = {
            'FLOW_UNITS': 'CMS',
            'INFILTRATION': 'HORTON',
            'FLOW_ROUTING': 'DYNWAVE',
            'FORCE_MAIN_EQUATION': 'H-W',
            'SURCHARGE_METHOD': 'SLOT',
            'VARIABLE_STEP': 0.75,
            'LENGTHENING_STEP': 0,
            'MIN_SURFAREA': 1.14,
            'NORMAL_FLOW_LIMITED': 'BOTH',
            'SKIP_STEADY_STATE': 'NO',
            'IGNORE_RAINFALL': 'NO',
            'IGNORE_SNOWMELT': 'NO',
            'IGNORE_GROUNDWATER': 'NO',
            'IGNORE_ROUTING': 'NO',
            'IGNORE_QUALITY': 'NO'
        }
        
        # Default time settings
        self.start_date = "01/01/2024"
        self.start_time = "00:00:00"
        self.end_date = "01/02/2024"
        self.end_time = "00:00:00"
        self.dry_days = 0
        self.report_step = "00:15:00"
        self.wet_step = "00:05:00"
        self.dry_step = "01:00:00"
        self.routing_step = "0:00:30"
        
    def create_header_sections(self, project_title):
        """Create header sections of SWMM input file"""
        content = []
        
        # Title section
        content.append("[TITLE]")
        content.append(f";;{project_title}")
        content.append(f";;Generated by SWMM Force Main App on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
        content.append("")
        
        # Options section (includes all time parameters)
        content.append("[OPTIONS]")
        for key, value in self.options.items():
            content.append(f"{key:<25} {value}")
        
        # Add time parameters to OPTIONS section
        content.append(f"{'START_DATE':<25} {self.start_date}")
        content.append(f"{'START_TIME':<25} {self.start_time}")
        content.append(f"{'REPORT_START_DATE':<25} {self.start_date}")
        content.append(f"{'REPORT_START_TIME':<25} {self.start_time}")
        content.append(f"{'END_DATE':<25} {self.end_date}")
        content.append(f"{'END_TIME':<25} {self.end_time}")
        content.append(f"{'SWEEP_START':<25} 01/01")
        content.append(f"{'SWEEP_END':<25} 12/31")
        content.append(f"{'DRY_DAYS':<25} {self.dry_days}")
        content.append(f"{'REPORT_STEP':<25} {self.report_step}")
        content.append(f"{'WET_STEP':<25} {self.wet_step}")
        content.append(f"{'DRY_STEP':<25} {self.dry_step}")
        content.append(f"{'ROUTING_STEP':<25} {self.routing_step}")
        content.append("")
        
        # Evaporation section
        content.append("[EVAPORATION]")
        content.append(";;Data Source    Parameters")
        content.append(";;-------------- ----------------")
        content.append("CONSTANT         0.0")
        content.append("DRY_ONLY         NO")
        content.append("")
        
        # No raingages or timeseries needed for constant inflow
        
        return content
    
    def create_report_section(self):
        """Create report section only - time parameters are now in OPTIONS"""
        content = []
        
        content.append("[REPORT]")
        content.append(";;Reporting Options")
        content.append("INPUT      NO")
        content.append("CONTROLS   NO")
        content.append("SUBCATCHMENTS NONE")  
        content.append("NODES ALL")
        content.append("LINKS ALL")
        content.append("")
        
        return content
    
    def create_coordinates_section(self, config, system_type='force_main'):
        """Create coordinates section for network visualization"""
        content = []
        
        content.append("[COORDINATES]")
        content.append(";;Node           X-Coord            Y-Coord           ")
        content.append(";;-------------- ------------------ ------------------")
        
        if system_type == 'force_main':
            # Create linear layout for force main system
            ww = config['wet_well']
            fm = config['force_main'] 
            dn = config['discharge_node']
            pump_discharge_node = fm['from']
            
            # Wet well at origin
            content.append(f"{ww['id']:<16} {0.0:<18.2f} {0.0:<18.2f}")
            
            # Pump discharge node slightly offset
            content.append(f"{pump_discharge_node:<16} {100.0:<18.2f} {0.0:<18.2f}")
            
            # Discharge node along the force main
            force_main_length = fm.get('length', 1000)
            x_discharge = 100.0 + force_main_length * 0.8
            content.append(f"{dn['id']:<16} {x_discharge:<18.2f} {0.0:<18.2f}")
            
            # Outfall at the end
            x_outfall = x_discharge + 100.0
            content.append(f"{'OUTFALL1':<16} {x_outfall:<18.2f} {0.0:<18.2f}")
            
        elif system_type == 'network':
            # For network systems, use provided coordinates or generate them
            nodes = config.get('nodes', {})
            x_offset = 0
            y_offset = 0
            
            for node_id, node in nodes.items():
                x_coord = node.get('x_coord', x_offset)
                y_coord = node.get('y_coord', y_offset)
                content.append(f"{node_id:<16} {x_coord:<18.2f} {y_coord:<18.2f}")
                
                # Auto-increment if no coordinates provided
                if 'x_coord' not in node:
                    x_offset += 200
                    
        content.append("")
        return content
    
