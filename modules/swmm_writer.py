    def create_network_system(self, nodes, links, pumps):
        """
        Create complex network system from node/link data
        
        Parameters:
        nodes: Dictionary of node configurations
        links: Dictionary of link configurations  
        pumps: Dictionary of pump configurations
        """
        content = []
        
        # Header
        content.extend(self.create_header_sections("Force Main Network"))
        
        # Process nodes
        junctions = []
        storage_nodes = []
        outfalls = []
        
        for node_id, node in nodes.items():
            if node['type'] == 'junction':
                junctions.append(node_id)
            elif node['type'] == 'wet_well':
                storage_nodes.append(node_id)
            elif node['type'] == 'outfall':
                outfalls.append(node_id)
        
        # Junctions section
        if junctions:
            content.append("[JUNCTIONS]")
            content.append(";;Name           Elevation  MaxDepth   InitDepth  SurDepth   Aponded   ")
            content.append(";;-------------- ---------- ---------- ---------- ---------- ----------")
            
            for node_id in junctions:
                node = nodes[node_id]
                # Ensure surcharge depth is at least 100 for force main nodes
                surcharge_depth = max(node.get('surcharge_depth', 100.0), 100.0)
                content.append(f"{node_id:<16} {node['invert']:<10.2f} {node.get('max_depth', 2.0):<10.2f} {0.0:<10.2f} {surcharge_depth:<10.2f} {0.0:<10.2f}")
            content.append("")
        
        # Storage section
        if storage_nodes:
            content.append("[STORAGE]")
            content.append(";;Name           Elev.    MaxDepth   InitDepth  Shape      Curve Name/Params            N/A      Fevap    Psi      Ksat     IMD     ")
            content.append(";;-------------- -------- ---------- ----------- ---------- ---------------------------- -------- -------- -------- -------- --------")
            
            for node_id in storage_nodes:
                node = nodes[node_id]
                content.append(f"{node_id:<16} {node['invert']:<8.2f} {node['max_depth']:<10.2f} {node.get('init_depth', 1.0):<10.2f} {'FUNCTIONAL':<10} {node.get('area', 50.0):<8.2f} 0 0 0 {0.0:<8.2f} {0.0:<8.2f} {0.0:<8.2f} {0.0:<8.2f}")
            content.append("")
        
        # Outfalls section
        if outfalls:
            content.append("[OUTFALLS]")
            content.append(";;Name           Elevation  Type       Stage Data       Gated    Route To        ")
            content.append(";;-------------- ---------- ---------- ---------------- -------- ----------------")
            
            for node_id in outfalls:
                node = nodes[node_id]
                content.append(f"{node_id:<16} {node['invert']:<10.2f} {'FREE':<10} {'':<16} {'NO':<8} {'':<16}")
            content.append("")
        
        # Conduits section
        content.append("[CONDUITS]")
        content.append(";;Name           From Node        To Node          Length     Roughness  InOffset   OutOffset  InitFlow   MaxFlow   ")
        content.append(";;-------------- ---------------- ---------------- ---------- ---------- ---------- ---------- ---------- ----------")
        
        for link_id, link in links.items():
            if link['type'] == 'force_main':
                content.append(f"{link_id:<16} {link['from']:<16} {link['to']:<16} {link['length']:<10.2f} {link['roughness']:<10.4f} {0.0:<10.2f} {0.0:<10.2f} {0.0:<10.2f} {0.0:<10.2f}")
        content.append("")
        
        # Pumps section
        if pumps:
            content.append("[PUMPS]")
            content.append(";;Name           From Node        To Node          Pump Curve       Status   Sartup Shutoff ")
            content.append(";;-------------- ---------------- ---------------- ---------------- ------ -------- --------")
            
            for pump_id, pump in pumps.items():
                content.append(f"{pump_id:<16} {pump['from']:<16} {pump['to']:<16} {pump['curve']:<16} {'ON':<6} {pump.get('startup', 2.0):<8.2f} {pump.get('shutoff', 0.5):<8.2f}")
            content.append("")
        
        # Cross-sections
        content.append("[XSECTIONS]")
        content.append(";;Link           Shape        Geom1            Geom2      Geom3      Geom4      Barrels    Culvert   ")
        content.append(";;-------------- ------------ ---------------- ---------- ---------- ---------- ---------- ----------")
        
        for link_id, link in links.items():
            if link['type'] == 'force_main':
                # Geom2 for FORCE_MAIN should be HW C coefficient (not Manning's n)
                hw_c = 120 if link['roughness'] < 1 else link['roughness']  # Convert Manning's n to HW C if needed
                content.append(f"{link_id:<16} {'FORCE_MAIN':<12} {link['diameter']:<16.3f} {hw_c:<10.3f} {0:<10.3f} {0:<10.3f} {1:<10} {0:<10}")
        content.append("")
        
        # Pump curves
        if pumps:
            content.append("[CURVES]")
            content.append(";;Name           Type       X-Value    Y-Value   ")
            content.append(";;-------------- ---------- ---------- ----------")
            
            for pump_id, pump in pumps.items():
                if 'curve_data' in pump and pump['curve_data']:
                    # First line has curve name and pump type
                    flow, head = pump['curve_data'][0]
                    content.append(f"{pump['curve']:<16} {'Pump3':<10} {flow:<10.4f} {head:<10.2f}")
                    
                    # Subsequent lines have only curve name and values
                    for flow, head in pump['curve_data'][1:]:
                        content.append(f"{pump['curve']:<16} {'':<10} {flow:<10.4f} {head:<10.2f}")
            content.append("")
        
        # Coordinates section for network visualization
        content.extend(self.create_coordinates_section({'nodes': nodes}, 'network'))
        
        # Report section
        content.extend(self.create_report_section())
        
        return "\n".join(content)
    
    def validate_input_file(self, inp_content):
        """
        Validate SWMM input file for common errors
        
        Returns:
        dict: Validation results
        """
        lines = inp_content.split('\n')
        errors = []
        warnings = []
        
        # Check for required sections
        required_sections = ['[TITLE]', '[OPTIONS]']
        found_sections = []
        
        for line in lines:
            line = line.strip()
            if line.startswith('[') and line.endswith(']'):
                found_sections.append(line)
        
        for section in required_sections:
            if section not in found_sections:
                errors.append(f"Missing required section: {section}")
        
        # Check for nodes and links
        has_nodes = any('[JUNCTIONS]' in s or '[STORAGE]' in s or '[OUTFALLS]' in s for s in found_sections)
        has_links = any('[CONDUITS]' in s or '[PUMPS]' in s for s in found_sections)
        
        if not has_nodes:
            errors.append("No nodes defined in model")
        if not has_links:
            warnings.append("No links defined in model")
        
        # Check for cross-sections if conduits exist
        if '[CONDUITS]' in found_sections and '[XSECTIONS]' not in found_sections:
            errors.append("Conduits defined but no cross-sections provided")
        
        return {
            'errors': errors,
            'warnings': warnings,
            'is_valid': len(errors) == 0,
            'sections_found': found_sections
        }
